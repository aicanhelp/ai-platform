// EnsureClusterYAML creates the remote compliance-hardening cluster.yaml from
// the resolved E2E node configuration when the file is absent. Existing files
// are preserved and validated by the suite. Credentials travel through SSH
// stdin and are never placed in the remote command or Ginkgo output.
func EnsureClusterYAML(e *executor.SSHExecutor, cfg *Config) (bool, error) {
	res, err := e.Exec(fmt.Sprintf("test -f %s", shellPath(cfg.ClusterYAML)))
	if err == nil && res != nil && res.ExitCode == 0 {
		return false, nil
	}
	if res == nil {
		return false, fmt.Errorf("检查 cluster.yaml 失败: %v", err)
	}
	if res.ExitCode != 1 {
		return false, fmt.Errorf("检查 cluster.yaml 失败（exit=%d）: %s", res.ExitCode, strings.TrimSpace(res.Stderr))
	}

	content, buildErr := renderClusterYAML(cfg)
	if buildErr != nil {
		return false, buildErr
	}
	configDir := path.Dir(cfg.ClusterYAML)
	cmd := fmt.Sprintf("install -d -m 700 %s && umask 077 && cat > %s && chmod 600 %s",
		shellPath(configDir), shellPath(cfg.ClusterYAML), shellPath(cfg.ClusterYAML))
	writeResult, writeErr := e.ExecWithInput(cmd, content)
	if writeErr != nil || writeResult == nil || writeResult.ExitCode != 0 {
		stderr := ""
		if writeResult != nil {
			stderr = strings.TrimSpace(writeResult.Stderr)
		}
		return false, fmt.Errorf("根据 E2E 环境生成 cluster.yaml 失败: %s", stderr)
	}
	return true, nil
}

func renderClusterYAML(cfg *Config) (string, error) {
	if len(cfg.Nodes) == 0 {
		return "", fmt.Errorf("无法生成 cluster.yaml：节点列表为空")
	}
	var b strings.Builder
	b.WriteString("# Generated by compliance-operator E2E from environment variables.\n")
	b.WriteString("# Contains credentials; keep this file on the entry node only.\n")
	b.WriteString("cluster:\n  ssh:\n    user: root\n    port: 22\n    connect_timeout: 15\n    default_password: ''\n  nodes:\n")
	for _, node := range cfg.Nodes {
		for field, value := range map[string]string{
			"ip": node.IP, "role": node.Role, "user": node.User, "password": node.Password,
		} {
			if strings.TrimSpace(value) == "" {
				return "", fmt.Errorf("无法生成 cluster.yaml：节点 %s 的 %s 为空", node.IP, field)
			}
			if strings.ContainsAny(value, "\r\n") {
				return "", fmt.Errorf("无法生成 cluster.yaml：节点 %s 的 %s 含换行符", node.IP, field)
			}
		}
		if node.Port <= 0 {
			return "", fmt.Errorf("无法生成 cluster.yaml：节点 %s 的 port 非法", node.IP)
		}
		fmt.Fprintf(&b, "    - ip: %s\n      role: %s\n      user: %s\n      password: %s\n      port: %d\n",
			yamlScalar(node.IP), yamlScalar(node.Role), yamlScalar(node.User), yamlScalar(node.Password), node.Port)
		if node.Hostname != "" {
			fmt.Fprintf(&b, "      hostname: %s\n", yamlScalar(node.Hostname))
		}
	}
	fmt.Fprintf(&b, "  strategy:\n    pod_recreate_wait: 30\n  backup_dir: %s\n  log_dir: %s\n  health_check_timeout: 180\n",
		yamlScalar(cfg.BackupDir), yamlScalar(cfg.LogDir))
	return b.String(), nil
}

func yamlScalar(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "''") + "'"
}

// ClusterHarden 在 entry_node 执行一键全集群加固/预检（extraArgs 如 -y / --dry-run）。
func ClusterHarden(e *executor.SSHExecutor, cfg *Config, extraArgs ...string) *executor.ExecResult {
	return ClusterHardenWithConfig(e, cfg, cfg.ClusterYAML, extraArgs...)
}

// ClusterHardenWithConfig 使用显式指定的 cluster.yaml 执行全集群加固/预检。
// 非法配置防护用例使用此入口，确保命令中只有被测配置路径。
func ClusterHardenWithConfig(e *executor.SSHExecutor, cfg *Config, clusterYAML string, extraArgs ...string) *executor.ExecResult {
	return Run(e, hardenCmd(cfg, "cluster-harden", clusterYAML, extraArgs...))
}

// ClusterRollback 在 entry_node 执行一键全集群回退（extraArgs 如 -y --backup-subdir <ts>）。
// stdinPrefix 用于交互确认场景（如 "echo n"）。
func ClusterRollback(e *executor.SSHExecutor, cfg *Config, stdinPrefix string, extraArgs ...string) *executor.ExecResult {
	cmd := hardenCmd(cfg, "cluster-rollback", cfg.ClusterYAML, extraArgs...)
	if stdinPrefix != "" {
		// 管道优先级：直接拼 "%s | %s" 会被 shell 解析为 (prefix | cd <dir>) && bash …，
		// cd 在管道子进程中执行、作用丢失，bash 在原 cwd 找不到脚本（exit 127，run7 实测）。
		// 用 bash -c 包裹整个复合命令，使 cd 与工具同 shell 且 stdin 经管道透传
		// （诊断师 entry_node 端到端实测通过：exit=0、确认块/取消提示/零修改均符合断言）。
		cmd = fmt.Sprintf("%s | bash -c %s", stdinPrefix, shellQuote(cmd))
	}
	return Run(e, cmd)
}

func hardenCmd(cfg *Config, sub, clusterYAML string, extraArgs ...string) string {
	return fmt.Sprintf("cd %s && bash bin/k8s-hardening.sh %s %s %s",
		shellPath(cfg.HardeningDir), sub, shellPath(clusterYAML), strings.Join(extraArgs, " "))
}

var unifiedTSRe = regexp.MustCompile(`本次集群加固备份时间戳（所有节点统一）：([0-9]{8}-[0-9]{6})`)

// ParseUnifiedTimestamp 从加固输出解析统一备份时间戳 TS（找不到返回空串）。
func ParseUnifiedTimestamp(output string) string {
	if m := unifiedTSRe.FindStringSubmatch(output); m != nil {
		return m[1]
	}
	return ""
}

// MasterSerialOrdered 校验输出含 [master i/N] 依次出现（严格串行）且 worker 并行段在其后。
func MasterSerialOrdered(output string, masterCount int) bool {
	lastPos := -1
	for i := 1; i <= masterCount; i++ {
		marker := fmt.Sprintf("[master %d/%d]", i, masterCount)
		pos := strings.Index(output, marker)
		if pos < 0 || pos <= lastPos {
			return false
		}
		lastPos = pos
	}
	wp := strings.Index(output, MsgWorkerParallel)
	return wp > lastPos
}

// ReportJSON 集群统一报告 JSON（lib/cluster.sh cluster_gen_report 结构）。
type ReportJSON struct {
	Timestamp string `json:"timestamp"`
	Summary   struct {
		Total      int `json:"total"`
		Remediated int `json:"remediated"`
		Skipped    int `json:"skipped"`
		Manual     int `json:"manual"`
		Error      int `json:"error"`
	} `json:"summary"`
	Nodes []struct {
		IP    string `json:"ip"`
		Label string `json:"label"`
		Role  string `json:"role"`
		State string `json:"state"` // hardened / no_pending_compliant / failed / no_result_data
		Rules []struct {
			RuleID string `json:"rule_id"`
			Source string `json:"source"`
			Status string `json:"status"` // remediated / skipped / manual / error
			Risk   string `json:"risk"`
		} `json:"rules"`
	} `json:"nodes"`
}

// NodeStates 返回 ip → state 映射。
func (r *ReportJSON) NodeStates() map[string]string {
	m := map[string]string{}
	for _, n := range r.Nodes {
		m[n.IP] = n.State
	}
	return m
}

// RuleStatuses 返回指定规则在各节点的状态（ip → status；remediated/skipped/manual/error）。
func (r *ReportJSON) RuleStatuses(ruleID string) map[string]string {
	m := map[string]string{}
	for _, n := range r.Nodes {
		for _, rule := range n.Rules {
			if rule.RuleID == ruleID {
				m[n.IP] = rule.Status
			}
		}
	}
	return m
}

// LatestReport 取 entry_node 上最新一份集群统一报告（kind: harden/rollback 场景均用 cluster-harden-report-*）。
func LatestReport(e *executor.SSHExecutor, reportDir string) (path string, content []byte, err error) {
	out, err := ExecTrim(e, fmt.Sprintf("ls -1t %s/%s 2>/dev/null | head -1", shellPath(reportDir), ReportJSONGlob))
	if err != nil {
		return "", nil, err
	}
	if out == "" {
		return "", nil, fmt.Errorf("%s 下未找到 %s", reportDir, ReportJSONGlob)
	}
	path = out
	raw, err := ExecTrim(e, fmt.Sprintf("cat %s", shellPath(path)))
	if err != nil {
		return path, nil, err
	}
	return path, []byte(raw), nil
}

// ParseReport 解析报告 JSON。
func ParseReport(raw []byte) (*ReportJSON, error) {
	var r ReportJSON
	if err := json.Unmarshal(raw, &r); err != nil {
		return nil, fmt.Errorf("报告 JSON 解析失败: %w", err)
	}
	return &r, nil
}

// ReadStateFile 读取 entry_node 工作目录下的状态文件（如首轮统一时间戳，供跨进程续跑）。
func ReadStateFile(e *executor.SSHExecutor, cfg *Config, name string) (string, error) {
	out, err := ExecTrim(e, fmt.Sprintf("cat %s/%s 2>/dev/null", shellPath(cfg.WorkDir), name))
	if err != nil || out == "" {
		return "", nil // 文件不存在不是错误
	}
	return strings.TrimSpace(out), nil
}

// WriteStateFile 写 entry_node 状态文件（目录 700，仅 root 可读）。
func WriteStateFile(e *executor.SSHExecutor, cfg *Config, name, content string) error {
	_, err := ExecTrim(e, fmt.Sprintf("mkdir -p %s && chmod 700 %s && printf '%%s\\n' %s > %s/%s",
		shellPath(cfg.WorkDir), shellPath(cfg.WorkDir), shellQuote(content), shellPath(cfg.WorkDir), name))
	return err
}

// ClusterYAMLNodeIPs 从 cluster.yaml 读取节点 IP 清单（yq，仅读非敏感字段）。
func ClusterYAMLNodeIPs(e *executor.SSHExecutor, cfg *Config) ([]string, error) {
	out, err := ExecTrim(e, fmt.Sprintf("yq -r '.cluster.nodes[].ip' %s 2>/dev/null", shellPath(cfg.ClusterYAML)))
	if err != nil {
		return nil, err
	}
	var ips []string
	for _, l := range strings.Split(out, "\n") {
		if ip := strings.TrimSpace(l); ip != "" {
			ips = append(ips, ip)
		}
	}
	return ips, nil
}

// ClusterYAMLLabelByIP 返回 ip → 展示名（hostname // ip）映射。
func ClusterYAMLLabelByIP(e *executor.SSHExecutor, cfg *Config) (map[string]string, error) {
	out, err := ExecTrim(e, fmt.Sprintf(
		`yq -r '.cluster.nodes[] | (.ip) + " " + (.hostname // .ip)' %s 2>/dev/null`, shellPath(cfg.ClusterYAML)))
	if err != nil {
		return nil, err
	}
	m := map[string]string{}
	for _, l := range strings.Split(out, "\n") {
		f := strings.Fields(strings.TrimSpace(l))
		if len(f) == 2 {
			m[f[0]] = f[1]
		}
	}
	return m, nil
}

// ClusterYAMLHasNodeOverride 检查 cluster.yaml 是否存在节点级 password 覆盖
// （只输出 ip，不回显口令本身；对应 E2E-A 前置 3 的混合凭据形态）。
func ClusterYAMLHasNodeOverride(e *executor.SSHExecutor, cfg *Config) (bool, error) {
	out, err := ExecTrim(e, fmt.Sprintf(
		`yq -r '.cluster.nodes[] | select(has("password")) | .ip' %s 2>/dev/null | grep -c . || true`, shellPath(cfg.ClusterYAML)))
	if err != nil {
		return false, err
	}
	return strings.TrimSpace(out) != "0" && strings.TrimSpace(out) != "", nil
}

// PrepareWorkDir 在 entry_node 建测试工作目录（指纹/复扫产物/状态文件落盘处）。
