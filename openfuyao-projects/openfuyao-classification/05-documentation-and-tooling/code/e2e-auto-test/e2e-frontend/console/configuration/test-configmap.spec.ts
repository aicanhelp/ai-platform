const LIST_PATH = '/container_platform/configuration/configMap';
const CONFIGMAP_YAML = readStaticYaml('valid-configmap.yaml');
const NAME_PREFIX = 'test-configmap';
const COPY_PREFIX = 'test-configmap-copy';
const NS = 'default';
const PLURAL = 'configmaps';

const createConfigMapViaApi = async (apiContext: APIRequestContext, name: string): Promise<void> => {
  await createFromYamlViaApi(apiContext, {
    yaml: CONFIGMAP_YAML,
    name,
    plural: PLURAL,
    namespace: NS,
  });
};

const deleteConfigMapViaApi = async (apiContext: APIRequestContext, name: string): Promise<void> => {
  await deleteResourceViaApi(apiContext, { plural: PLURAL, name, namespace: NS });
};

test.describe('创建configmap', () => {
  test.beforeEach(async ({ page }) => {
    await page.goto(FUYAO_BASE_URL + LIST_PATH);
  });

  test.afterEach(async ({ request }) => {
    await deleteConfigMapViaApi(request, uniqueResourceName(NAME_PREFIX));
  });

  test('【资源管理-216】 配置与密钥-ConfigMap，取消创建ConfigMap成功', {
    tag: ['@v24.06', '@k8s'],
  }, async ({ page }) => {
    const name = uniqueResourceName(NAME_PREFIX);
    await clickCreate(page);
    await fillYaml(page, CONFIGMAP_YAML, name);
    await cancelCreateOrEdit(page);
    await searchResource(page, name);
    await expect(page.getByText('暂无数据')).toBeVisible({ timeout: 5000 });
  });

  test('【资源管理-212】 配置与密钥-ConfigMap，输入格式有误的yaml创建ConfigMap失败有提示', {
    tag: ['@v24.06', '@k8s'],
  }, async ({ page }) => {
    await clickCreate(page);
    await fillYaml(page, CONFIGMAP_YAML, uniqueResourceName(NAME_PREFIX), (yaml) => yaml.replace(/^\s+/gm, ''));
    await saveCreateOrEdit(page);
    await expectErrorMessage(page, /YAML格式不规范|创建失败/);
  });

  test('【资源管理-213】 配置与密钥-ConfigMap，输入字段有误的yaml创建ConfigMap失败有提示', {
    tag: ['@v24.06', '@k8s'],
  }, async ({ page }) => {
    const name = uniqueResourceName(NAME_PREFIX);
    await clickCreate(page);
    await fillYaml(page, CONFIGMAP_YAML, name, (yaml) => yaml.replace(/(\s*key\d): .*/g, '$1: 1'));
    await saveCreateOrEdit(page);
    await expectErrorMessage(page);
  });

  test('【资源管理-215】 配置与密钥-ConfigMap，使用不存在的namespace创建，应提示', {
    tag: ['@v24.06', '@k8s'],
  }, async ({ page }) => {
    const name = uniqueResourceName(NAME_PREFIX);
    await clickCreate(page);
    await fillYaml(page, CONFIGMAP_YAML, name, (yaml) => yaml.replace(/namespace: default/g, 'namespace: non-existing-ns'));
    await saveCreateOrEdit(page);
    await expectErrorMessage(page, 'namespaces "non-existing-ns" not found');
  });

  test('【资源管理-211】 配置与密钥-ConfigMap，输入正确yaml创建ConfigMap成功', {
    tag: ['@v24.06', '@k8s'],
  }, async ({ page }) => {
    const name = uniqueResourceName(NAME_PREFIX);
    await clickCreate(page);
    await fillYaml(page, CONFIGMAP_YAML, name);
    await saveCreateOrEdit(page);
    await expectSuccessMessage(page);
    await searchResource(page, name);
    await expect(page.getByRole('row', { name }).first()).toBeVisible({ timeout: 10000 });
  });

  test('【资源管理-217】 配置与密钥-ConfigMap，短时间连续点击创建按钮时，查看页面提示', {
    tag: ['@v24.06', '@k8s', '@skip-temporarily'],
  }, async ({ page }) => {
    const name = uniqueResourceName(NAME_PREFIX);
    await clickCreate(page);
    await fillYaml(page, CONFIGMAP_YAML, name);
    await saveCreateOrEdit(page);
    await saveCreateOrEdit(page);
    await expectSuccessMessage(page);
    await expectErrorMessage(page, /configmaps ".*" already exists/);
    await searchResource(page, name);
    await expect(page.getByRole('row', { name }).first()).toBeVisible({ timeout: 10000 });
  });
});

